-- Self-Service Multi-Question Password Recovery & Removal of Admin Password-Change Authority
-- Run AFTER supabase/migration-multiplayer-rooms-realtime.sql.

-- 1. Private table storing salted bcrypt hashes of normalized player recovery answers
create table if not exists public.user_security_questions (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  question_id text not null,
  question_prompt text not null,
  answer_hash text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint user_security_questions_uid_qid_uniq unique (user_id, question_id)
);

create index if not exists user_security_questions_user_idx
  on public.user_security_questions (user_id, id asc);

alter table public.user_security_questions enable row level security;
revoke all on public.user_security_questions from public, anon, authenticated;

-- 2. Answer normalizer (trim, collapse whitespace, lowercase) & prompt validator
create or replace function public._normalize_security_answer(p_answer text)
returns text
language sql
immutable
as $$
  select lower(btrim(regexp_replace(coalesce(p_answer, ''), '\s+', ' ', 'g')));
$$;
revoke all on function public._normalize_security_answer(text) from public, anon, authenticated;

-- 3. Update _serialize_auth_user to expose security_question_count (count only, never answers/hashes)
create or replace function public._serialize_auth_user(p_user public.users)
returns jsonb
language sql
stable
set search_path = public, extensions, pg_temp
as $$
  select jsonb_build_object(
    'id', p_user.id,
    'username_key', p_user.username_key,
    'display_name', p_user.display_name,
    'best_score', p_user.best_score,
    'total_kills', p_user.total_kills,
    'total_correct', p_user.total_correct,
    'total_answers', p_user.total_answers,
    'topic_progress', p_user.topic_progress,
    'skill_progress', p_user.skill_progress,
    'review_store', p_user.review_store,
    'achievements', p_user.achievements,
    'is_suspended', coalesce(p_user.is_suspended, false),
    'must_change_password', coalesce(p_user.must_change_password, false),
    'failed_login_count', coalesce(p_user.failed_login_count, 0),
    'last_failed_login_at', p_user.last_failed_login_at,
    'security_question_count', (select count(*)::integer from public.user_security_questions q where q.user_id = p_user.id),
    'created_at', p_user.created_at,
    'updated_at', p_user.updated_at,
    'last_login_at', p_user.last_login_at
  );
$$;
revoke all on function public._serialize_auth_user(public.users) from public, anon, authenticated;

-- 4. Update auth_sign_up to require 2-3 distinct security recovery questions + Academic Year
drop function if exists public.auth_sign_up(text, text);

create or replace function public.auth_sign_up(
  p_username text,
  p_password text,
  p_academic_year integer default 4,
  p_security_questions jsonb default '[]'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_display_name text := btrim(regexp_replace(coalesce(p_username, ''), '\s+', ' ', 'g'));
  v_username_key text := lower(v_display_name);
  v_password text := coalesce(p_password, '');
  v_year integer := case when coalesce(p_academic_year, 4) between 1 and 4 then p_academic_year else 4 end;
  v_password_hash text;
  v_user public.users;
  v_session_token text;
  v_token_hash text;
  v_expires_at timestamptz := now() + interval '30 days';
  v_item jsonb;
  v_qid text;
  v_prompt text;
  v_ans text;
  v_seen text[] := '{}'::text[];
  v_count integer := 0;
begin
  if char_length(v_display_name) not between 1 and 24 then
    raise exception 'AUTH_INVALID_USERNAME: Username must be between 1 and 24 characters.';
  end if;

  if char_length(v_password) < 6 or char_length(v_password) > 72 or char_length(btrim(v_password)) = 0 then
    raise exception 'AUTH_INVALID_PASSWORD: Password must be between 6 and 72 characters.';
  end if;

  if jsonb_typeof(coalesce(p_security_questions, '[]'::jsonb)) <> 'array' then
    raise exception 'AUTH_SECURITY_QUESTIONS_REQUIRED: Please pick and answer at least 2 security recovery questions.';
  end if;

  v_count := jsonb_array_length(p_security_questions);
  if v_count < 2 or v_count > 3 then
    raise exception 'AUTH_SECURITY_QUESTIONS_REQUIRED: Please pick and answer 2 or 3 distinct security recovery questions.';
  end if;

  for v_item in select * from jsonb_array_elements(p_security_questions) loop
    v_qid := lower(btrim(coalesce(v_item->>'id', '')));
    v_prompt := btrim(regexp_replace(coalesce(v_item->>'prompt', ''), '\s+', ' ', 'g'));
    v_ans := public._normalize_security_answer(v_item->>'answer');
    if v_qid = '' or v_prompt = '' or char_length(v_qid) > 40 or char_length(v_prompt) > 160 then
      raise exception 'AUTH_SECURITY_QUESTIONS_INVALID: Invalid recovery question selected.';
    end if;
    if v_qid = any(v_seen) then
      raise exception 'AUTH_SECURITY_QUESTIONS_DUPLICATE: Each recovery question must be different.';
    end if;
    if char_length(v_ans) < 2 or char_length(v_ans) > 80 then
      raise exception 'AUTH_SECURITY_ANSWER_INVALID: Each recovery answer must be between 2 and 80 characters.';
    end if;
    v_seen := array_append(v_seen, v_qid);
  end loop;

  begin
    insert into public.users (
      username_key,
      display_name,
      topic_progress,
      skill_progress,
      review_store,
      achievements,
      last_login_at,
      updated_at
    )
    values (
      v_username_key,
      v_display_name,
      '{}'::jsonb,
      '{}'::jsonb,
      jsonb_build_object('academicYear', v_year),
      '{}'::jsonb,
      now(),
      now()
    )
    returning * into v_user;
  exception
    when unique_violation then
      raise exception 'AUTH_USERNAME_TAKEN: That username is already taken. Please choose another name.';
  end;

  v_password_hash := crypt(v_password, gen_salt('bf'::text, 12));

  insert into public.user_credentials (user_id, password_hash, created_at, updated_at)
  values (v_user.id, v_password_hash, now(), now());

  for v_item in select * from jsonb_array_elements(p_security_questions) loop
    v_qid := lower(btrim(v_item->>'id'));
    v_prompt := btrim(regexp_replace(v_item->>'prompt', '\s+', ' ', 'g'));
    v_ans := public._normalize_security_answer(v_item->>'answer');
    insert into public.user_security_questions (user_id, question_id, question_prompt, answer_hash, created_at, updated_at)
    values (v_user.id, v_qid, v_prompt, crypt(v_ans, gen_salt('bf'::text, 12)), now(), now());
  end loop;

  insert into public.admin_audit_logs (actor, action, target, detail)
  values (v_display_name, 'PLAYER_SIGNUP', v_display_name, 'Signed up (Year ' || v_year || ', ' || v_count || ' recovery questions)');

  v_session_token := encode(gen_random_bytes(32), 'hex');
  v_token_hash := encode(digest(convert_to(v_session_token, 'utf8'), 'sha256'::text), 'hex');

  insert into public.user_sessions (token_hash, user_id, created_at, expires_at)
  values (v_token_hash, v_user.id, now(), v_expires_at);

  return jsonb_build_object(
    'session_token', v_session_token,
    'expires_at', v_expires_at,
    'user', public._serialize_auth_user(v_user)
  );
end;
$$;
revoke all on function public.auth_sign_up(text, text, integer, jsonb) from public, anon, authenticated;
grant execute on function public.auth_sign_up(text, text, integer, jsonb) to anon, authenticated;

-- 5. Self-service Forgot Password Step 1: fetch saved recovery question prompts (never answers/hashes)
create or replace function public.auth_get_security_questions(p_username text)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_display_name text := btrim(regexp_replace(coalesce(p_username, ''), '\s+', ' ', 'g'));
  v_username_key text := lower(v_display_name);
  v_rl record;
  v_user public.users;
  v_questions jsonb;
begin
  select * into v_rl from public._check_rate_limit('secq-lookup:' || coalesce(nullif(v_username_key, ''), 'blank'), 10, 600, true);
  if not coalesce(v_rl.allowed, true) then
    return jsonb_build_object(
      'ok', false,
      'code', 'RATE_LIMITED',
      'retry_after', v_rl.retry_after,
      'error', 'Too many recovery lookups. Please wait ' || v_rl.retry_after || ' seconds and try again.'
    );
  end if;

  if char_length(v_display_name) not between 1 and 24 then
    return jsonb_build_object('ok', false, 'code', 'INVALID_USERNAME', 'error', 'Enter your username (1 to 24 characters).');
  end if;

  select * into v_user from public.users where username_key = v_username_key;
  if v_user.id is null then
    return jsonb_build_object('ok', false, 'code', 'ACCOUNT_NOT_FOUND', 'error', 'No account found with username "' || v_display_name || '". Check your spelling or sign up first.');
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
    'id', q.question_id,
    'prompt', q.question_prompt
  ) order by q.id asc), '[]'::jsonb)
  into v_questions
  from public.user_security_questions q
  where q.user_id = v_user.id;

  if jsonb_array_length(v_questions) = 0 then
    return jsonb_build_object(
      'ok', false,
      'code', 'NO_SECURITY_QUESTIONS',
      'error', 'This account has no recovery questions saved yet. If you still remember your password, log in and add recovery questions in Settings.'
    );
  end if;

  return jsonb_build_object(
    'ok', true,
    'username', v_user.display_name,
    'questions', v_questions
  );
end;
$$;
revoke all on function public.auth_get_security_questions(text) from public, anon, authenticated;
grant execute on function public.auth_get_security_questions(text) to anon, authenticated;

-- 5b. Self-service Forgot Password Step 2: verify identity via saved security question BEFORE password step
create or replace function public.auth_verify_security_answer(
  p_username text,
  p_question_id text,
  p_answer text
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_display_name text := btrim(regexp_replace(coalesce(p_username, ''), '\s+', ' ', 'g'));
  v_username_key text := lower(v_display_name);
  v_qid text := lower(btrim(coalesce(p_question_id, '')));
  v_norm_ans text := public._normalize_security_answer(p_answer);
  v_bucket text := 'secq-reset:' || coalesce(nullif(v_username_key, ''), 'blank');
  v_rl record;
  v_user public.users;
  v_q public.user_security_questions;
  v_dummy_hash text := '$2a$12$C6UzMDM.H6dfI/f/IKxGhu6C8M7xT7P1z8xN4M2P5W6Q9yH2vK3aW';
begin
  select * into v_rl from public._check_rate_limit(v_bucket, 5, 900, false);
  if not coalesce(v_rl.allowed, true) then
    return jsonb_build_object(
      'ok', false,
      'code', 'RATE_LIMITED',
      'retry_after', v_rl.retry_after,
      'error', 'Too many incorrect recovery attempts. Please wait ' || v_rl.retry_after || ' seconds and try again.'
    );
  end if;

  if v_qid = '' then
    return jsonb_build_object('ok', false, 'code', 'INVALID_SECURITY_QUESTION', 'error', 'Choose a security recovery question.');
  end if;

  if char_length(v_norm_ans) < 2 then
    return jsonb_build_object('ok', false, 'code', 'INVALID_SECURITY_ANSWER', 'error', 'Enter your answer to the selected recovery question.');
  end if;

  select * into v_user from public.users where username_key = v_username_key;
  if v_user.id is null then
    perform public._check_rate_limit(v_bucket, 5, 900, true);
    return jsonb_build_object('ok', false, 'code', 'ACCOUNT_NOT_FOUND', 'error', 'Account not found.');
  end if;

  if coalesce(v_user.is_suspended, false) then
    return jsonb_build_object('ok', false, 'code', 'ACCOUNT_SUSPENDED', 'error', 'This account has been locked by an administrator.');
  end if;

  select * into v_q
  from public.user_security_questions
  where user_id = v_user.id and question_id = v_qid;

  if v_q.id is null or crypt(v_norm_ans, coalesce(v_q.answer_hash, v_dummy_hash)) <> coalesce(v_q.answer_hash, '') then
    perform public._check_rate_limit(v_bucket, 5, 900, true);
    return jsonb_build_object(
      'ok', false,
      'code', 'INVALID_SECURITY_ANSWER',
      'error', 'Incorrect answer. Double-check your spelling or choose one of your other recovery questions.'
    );
  end if;

  return jsonb_build_object(
    'ok', true,
    'verified', true,
    'username', v_user.display_name,
    'question_id', v_qid
  );
end;
$$;
revoke all on function public.auth_verify_security_answer(text, text, text) from public, anon, authenticated;
grant execute on function public.auth_verify_security_answer(text, text, text) to anon, authenticated;

-- 6. Self-service Forgot Password Step 3: verify saved question answer & reset password immediately
create or replace function public.auth_reset_password_with_security_question(
  p_username text,
  p_question_id text,
  p_answer text,
  p_new_password text
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_display_name text := btrim(regexp_replace(coalesce(p_username, ''), '\s+', ' ', 'g'));
  v_username_key text := lower(v_display_name);
  v_qid text := lower(btrim(coalesce(p_question_id, '')));
  v_norm_ans text := public._normalize_security_answer(p_answer);
  v_new_pw text := coalesce(p_new_password, '');
  v_bucket text := 'secq-reset:' || coalesce(nullif(v_username_key, ''), 'blank');
  v_rl record;
  v_user public.users;
  v_q public.user_security_questions;
  v_dummy_hash text := '$2a$12$C6UzMDM.H6dfI/f/IKxGhu6C8M7xT7P1z8xN4M2P5W6Q9yH2vK3aW';
begin
  select * into v_rl from public._check_rate_limit(v_bucket, 5, 900, false);
  if not coalesce(v_rl.allowed, true) then
    return jsonb_build_object(
      'ok', false,
      'code', 'RATE_LIMITED',
      'retry_after', v_rl.retry_after,
      'error', 'Too many incorrect recovery attempts. Please wait ' || v_rl.retry_after || ' seconds and try again.'
    );
  end if;

  if char_length(v_new_pw) < 6 or char_length(v_new_pw) > 72 or char_length(btrim(v_new_pw)) = 0 then
    return jsonb_build_object('ok', false, 'code', 'INVALID_PASSWORD', 'error', 'New password must be between 6 and 72 characters.');
  end if;

  if char_length(v_norm_ans) < 1 then
    return jsonb_build_object('ok', false, 'code', 'INVALID_SECURITY_ANSWER', 'error', 'Enter your answer to the selected recovery question.');
  end if;

  select * into v_user from public.users where username_key = v_username_key;
  if v_user.id is null then
    perform public._check_rate_limit(v_bucket, 5, 900, true);
    return jsonb_build_object('ok', false, 'code', 'ACCOUNT_NOT_FOUND', 'error', 'Account not found.');
  end if;

  if coalesce(v_user.is_suspended, false) then
    return jsonb_build_object('ok', false, 'code', 'ACCOUNT_SUSPENDED', 'error', 'This account has been locked by an administrator.');
  end if;

  select * into v_q
  from public.user_security_questions
  where user_id = v_user.id and question_id = v_qid;

  if v_q.id is null or crypt(v_norm_ans, coalesce(v_q.answer_hash, v_dummy_hash)) <> coalesce(v_q.answer_hash, '') then
    perform public._check_rate_limit(v_bucket, 5, 900, true);
    return jsonb_build_object(
      'ok', false,
      'code', 'INVALID_SECURITY_ANSWER',
      'error', 'Incorrect answer. Double-check your spelling or choose one of your other recovery questions.'
    );
  end if;

  perform public._clear_rate_limit(v_bucket);

  insert into public.user_credentials (user_id, password_hash, created_at, updated_at)
  values (v_user.id, crypt(v_new_pw, gen_salt('bf'::text, 12)), now(), now())
  on conflict (user_id) do update set password_hash = excluded.password_hash, updated_at = now();

  update public.users
  set must_change_password = false,
      failed_login_count = 0,
      last_failed_login_at = null,
      updated_at = now()
  where id = v_user.id;

  delete from public.user_sessions where user_id = v_user.id;

  insert into public.admin_audit_logs (actor, action, target, detail)
  values (v_user.display_name, 'SELF_PASSWORD_RESET', v_user.display_name, 'Reset own password via security question (' || v_qid || ')');

  return jsonb_build_object(
    'ok', true,
    'message', 'Password reset! You can now log in with your new password.'
  );
end;
$$;
revoke all on function public.auth_reset_password_with_security_question(text, text, text, text) from public, anon, authenticated;
grant execute on function public.auth_reset_password_with_security_question(text, text, text, text) to anon, authenticated;

-- 7. Authenticated Settings update for recovery questions (requires current password)
create or replace function public.auth_update_security_questions(
  p_session_token text,
  p_current_password text,
  p_security_questions jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions, pg_temp
as $$
declare
  v_user_id bigint;
  v_user public.users;
  v_stored_hash text;
  v_cur text := coalesce(p_current_password, '');
  v_item jsonb;
  v_qid text;
  v_prompt text;
  v_ans text;
  v_seen text[] := '{}'::text[];
  v_count integer := 0;
begin
  v_user_id := public._resolve_session_user_id(p_session_token);
  if v_user_id is null then
    raise exception 'AUTH_SESSION_INVALID: Your session has expired. Please log in again.';
  end if;

  select * into v_user from public.users where id = v_user_id;
  select password_hash into v_stored_hash from public.user_credentials where user_id = v_user_id;
  if v_stored_hash is null or crypt(v_cur, v_stored_hash) <> v_stored_hash then
    raise exception 'AUTH_INVALID_CREDENTIALS: Current password is incorrect.';
  end if;

  if jsonb_typeof(coalesce(p_security_questions, '[]'::jsonb)) <> 'array' then
    raise exception 'AUTH_SECURITY_QUESTIONS_REQUIRED: Pick and answer 2 or 3 distinct recovery questions.';
  end if;

  v_count := jsonb_array_length(p_security_questions);
  if v_count < 2 or v_count > 3 then
    raise exception 'AUTH_SECURITY_QUESTIONS_REQUIRED: Pick and answer 2 or 3 distinct recovery questions.';
  end if;

  for v_item in select * from jsonb_array_elements(p_security_questions) loop
    v_qid := lower(btrim(coalesce(v_item->>'id', '')));
    v_prompt := btrim(regexp_replace(coalesce(v_item->>'prompt', ''), '\s+', ' ', 'g'));
    v_ans := public._normalize_security_answer(v_item->>'answer');
    if v_qid = '' or v_prompt = '' or char_length(v_qid) > 40 or char_length(v_prompt) > 160 then
      raise exception 'AUTH_SECURITY_QUESTIONS_INVALID: Invalid recovery question selected.';
    end if;
    if v_qid = any(v_seen) then
      raise exception 'AUTH_SECURITY_QUESTIONS_DUPLICATE: Each recovery question must be different.';
    end if;
    if char_length(v_ans) < 2 or char_length(v_ans) > 80 then
      raise exception 'AUTH_SECURITY_ANSWER_INVALID: Each recovery answer must be between 2 and 80 characters.';
    end if;
    v_seen := array_append(v_seen, v_qid);
  end loop;

  delete from public.user_security_questions where user_id = v_user_id;
  for v_item in select * from jsonb_array_elements(p_security_questions) loop
    v_qid := lower(btrim(v_item->>'id'));
    v_prompt := btrim(regexp_replace(v_item->>'prompt', '\s+', ' ', 'g'));
    v_ans := public._normalize_security_answer(v_item->>'answer');
    insert into public.user_security_questions (user_id, question_id, question_prompt, answer_hash, created_at, updated_at)
    values (v_user_id, v_qid, v_prompt, crypt(v_ans, gen_salt('bf'::text, 12)), now(), now());
  end loop;

  update public.users set updated_at = now() where id = v_user_id;

  insert into public.admin_audit_logs (actor, action, target, detail)
  values (v_user.display_name, 'SECURITY_QUESTIONS_UPDATED', v_user.display_name, 'Configured ' || v_count || ' self-service recovery question(s)');

  return jsonb_build_object('ok', true, 'security_question_count', v_count);
end;
$$;
revoke all on function public.auth_update_security_questions(text, text, jsonb) from public, anon, authenticated;
grant execute on function public.auth_update_security_questions(text, text, jsonb) to anon, authenticated;

