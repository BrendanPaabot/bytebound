// Builds js/data/questions.js from data/questions.json and checks the question bank.
// Usage (from the project folder):  node scripts/build-questions.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const source = JSON.parse(fs.readFileSync(path.join(root, 'data', 'questions.json'), 'utf8'));
const LEVELS = ['easy', 'medium', 'hard'];
const MIN_PER_LEVEL = 3;

const errors = [];
const warnings = [];
const seenText = new Set();
const coverage = {};
const output = {};

for (const key of Object.keys(source)) {
  if (!LEVELS.includes(key)) errors.push(`Unknown difficulty "${key}" (use easy, medium, hard)`);
}

for (const level of LEVELS) {
  const list = source[level];
  if (!Array.isArray(list)) {
    errors.push(`Missing list for "${level}"`);
    continue;
  }
  output[level] = [];
  list.forEach((item, index) => {
    const where = `${level}[${index}]`;
    if (typeof item.category !== 'string' || !item.category.trim()) errors.push(`${where}: missing category`);
    if (typeof item.topic !== 'string' || !item.topic.trim()) errors.push(`${where}: missing topic`);
    if (typeof item.q !== 'string' || !item.q.trim()) errors.push(`${where}: missing question text`);
    if (!Array.isArray(item.choices) || item.choices.length !== 4 || item.choices.some((c) => typeof c !== 'string' || !c.trim())) {
      errors.push(`${where}: needs exactly 4 non-empty choices`);
    } else if (new Set(item.choices).size !== 4) {
      errors.push(`${where}: choices must be different from each other`);
    }
    if (!Number.isInteger(item.answer) || item.answer < 0 || item.answer > 3) errors.push(`${where}: answer must be 0, 1, 2, or 3`);
    if (typeof item.explain !== 'string' || !item.explain.trim()) errors.push(`${where}: missing explanation`);
    if (seenText.has(item.q)) errors.push(`${where}: duplicate question text`);
    seenText.add(item.q);

    const topicKey = `${item.category} / ${item.topic}`;
    coverage[topicKey] = coverage[topicKey] || { easy: 0, medium: 0, hard: 0 };
    coverage[topicKey][level] += 1;

    // Keep only the fields the game uses; `objective` and `resource` are optional extras for later.
    output[level].push({
      category: item.category,
      topic: item.topic,
      q: item.q,
      choices: item.choices,
      answer: item.answer,
      explain: item.explain,
    });
  });
}

for (const [topicKey, counts] of Object.entries(coverage)) {
  for (const level of LEVELS) {
    if (counts[level] < MIN_PER_LEVEL) {
      warnings.push(`${topicKey}: ${counts[level]} ${level} question(s), aim for ${MIN_PER_LEVEL} or more`);
    }
  }
}

console.log('Question bank summary');
for (const level of LEVELS) console.log(`  ${level.padEnd(7)} ${(output[level] || []).length}`);
console.log(`  topics  ${Object.keys(coverage).length}`);

if (warnings.length) {
  console.log(`\nCoverage warnings (${warnings.length}):`);
  warnings.forEach((w) => console.log(`  - ${w}`));
}

if (errors.length) {
  console.error(`\nNot built. ${errors.length} problem(s) found:`);
  errors.forEach((e) => console.error(`  - ${e}`));
  process.exit(1);
}

const header = [
  '// Generated by scripts/build-questions.js from data/questions.json.',
  '// Edit data/questions.json, then run: node scripts/build-questions.js',
  '// `answer` is the index of the correct choice.',
  '',
].join('\n');
fs.writeFileSync(path.join(root, 'js', 'data', 'questions.js'), `${header}const QUESTION_BANK = ${JSON.stringify(output, null, 2)};\n`);
console.log('\nWrote js/data/questions.js');
